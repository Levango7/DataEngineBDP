-- Flyway 迁移 V3：承接租户域的两张表 quotas / workspaces
--
-- 为什么由本模块建（而不是留给 platform/encaps-tenant）：
--   encaps-tenant 的持久单元里含 encaps-layer 的实体（它直接注入 TenantRepository /
--   ProjectRepository / ApiDefinitionRepository / AssetRepository / DataSourceRepository /
--   SyncTaskRepository，EncapsTenantApplication 又是裸 @SpringBootApplication 且与其
--   实体同包根 com.levango7.dataenginebdp.encaps），所以它的 validate 需要本模块的
--   全部 20 张表都在同一个 schema 里 —— 这正是 KNOWN-FAILURES #63 的现象
--   （Schema validation: missing table [api_definition]）。
--
--   处置口径：**一个 schema 只允许一个 Flyway owner**。encaps-tenant 的 prod 现改为
--   指向本 schema（currentSchema=encaps_layer）且 flyway.enabled=false；两张它独有的表
--   随之并入本模块的迁移，否则 encaps-tenant 的 V1 与本模块的 V1 会在同一个
--   flyway_schema_history 上撞 checksum。
--
--   代价（如实记录）：本模块的 Flyway 从此也负责另外两个模块域的表。彻底解法是让
--   encaps-tenant 不再注入 encaps-layer 的 Repository（改走 REST），使其持久单元收缩到
--   自己的实体 —— 那属结构性重构，不在本迁移范围。
--
-- 表结构与列类型依据（逐字段对照实体，不是凭记忆写）：
--   Quota.java:34 @Table(name="quotas")；:38-40 id(Long,@Id,@GeneratedValue(IDENTITY))
--     :43 workspaceId(Long)  :47 tenantId(String，租户业务键)
--     :52-77 ResourceQuota 组 6 个 String（cpuLimit/memoryLimit/storageLimit-podLimit/pvcLimit/serviceLimit）
--     :82-92 LimitRange 组 4 个 String（maxCpuPerPod/maxMemoryPerPod/minCpuPerPod/minMemoryPerPod）
--     :96-97 status(@Enumerated(EnumType.STRING) -> varchar(255))
--     :101-104 createdAt/updatedAt(LocalDateTime -> timestamp(6))
--     QuotaStatus 枚举见 :114-127
--   Workspace.java:36 @Table(name="workspaces")；:40-42 id(同上)
--     :46 name(String)  :50 tenantId(String)
--     :54 description  :58 status(@Enumerated(STRING))  :62 namespace
--     :66 resourceQuota  :70 networkPolicy  :74-77 createdAt/updatedAt
--
-- 与 encaps-tenant 旧 V1/V2 的关系：其 V1 把 tenant_id 建成 bigint、再由 V2 ALTER 成
-- varchar(255)。这里直接以 varchar(255) 建表，等价于它俩叠加后的终态，不需要两步走。
-- 实体上的 @NotBlank/@NotNull 属 Bean Validation，Hibernate 6+ 不据此生成 NOT NULL，
-- 故对应列保持可空（应用层校验）——与 V1 生成口径一致。

create table quotas (
    id                 bigint generated by default as identity,
    workspace_id       bigint,
    tenant_id          varchar(255),
    cpu_limit          varchar(255),
    memory_limit       varchar(255),
    storage_limit      varchar(255),
    pod_limit          varchar(255),
    pvc_limit          varchar(255),
    service_limit      varchar(255),
    max_cpu_per_pod    varchar(255),
    max_memory_per_pod varchar(255),
    min_cpu_per_pod    varchar(255),
    min_memory_per_pod varchar(255),
    status             varchar(255),
    created_at         timestamp(6),
    updated_at         timestamp(6),
    primary key (id)
);

create table workspaces (
    id             bigint generated by default as identity,
    name           varchar(255),
    tenant_id      varchar(255),
    description    varchar(255),
    status         varchar(255),
    namespace      varchar(255),
    resource_quota varchar(255),
    network_policy varchar(255),
    created_at     timestamp(6),
    updated_at     timestamp(6),
    primary key (id)
);
