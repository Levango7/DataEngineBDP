create table project (datasets integer not null, jobs integer not null, created_at timestamp(6) with time zone not null, id bigint generated by default as identity, updated_at timestamp(6) with time zone, status varchar(16) not null, domain varchar(64) not null, tenant_id varchar(64) not null, name varchar(128) not null, description varchar(512), primary key (id));

create table tenants (created_at timestamp(6), id bigint generated by default as identity, updated_at timestamp(6), display_name varchar(255), name varchar(255) not null, namespace varchar(255), quota_profile varchar(255), status varchar(255), primary key (id));
