--         ⇒ 不存在"已应用该 checksum"的环境；
--      ③ 若改用 V4「建完 18 张再 DROP 掉」的表达，对后来读者是纯误导。
--    若你的环境确实应用过旧版 V3，请勿直接使用本文件，改用 V4 迁移。
--
-- 变更原因（2026-10-13，抽 encaps-shared-model）：
--   旧 V3 之所以要建 20 张表，是因为 encaps-tenant 与 encaps-layer 共享包根
--   `com.levango7.dataenginebdp.encaps`，`@EntityScan` 取默认值 ⇒ 把 encaps-layer
--   的**全部 20 个实体**拉进本服务的持久单元，prod 走 ddl-auto=validate 时
--   这些表必须存在，否则启动即 "Schema validation: missing table [...]"。
--   但那 20 张表由 encaps-layer / encaps-gateway / encaps-data 写入
--   **encaps_layer** schema，本 schema 里的副本**永远是空的** —— 这就是
--   AdminController 那批统计"结构性恒 0"的根因。
--
--   现把 Tenant / ProjectEntity 抽到 encaps-shared-model（独立包根
--   `com.levango7.dataenginebdp.encapsshared`），并在 EncapsTenantApplication
--   的 @EntityScan 里**逐个列出**实体所属包（quota / workspace / shared），
--   不再列 `...encaps.model` ⇒ 持久单元收窄到 4 个实体、4 张表：
--       quotas, workspaces（V1） + tenants, project（本文件）
--
-- 请勿手工编辑本文件；实体变更后重跑生成器，并按差异新增 V4__xxx.sql
