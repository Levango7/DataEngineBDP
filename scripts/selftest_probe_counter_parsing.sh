#!/usr/bin/env bash
# 本地夹具自测 + 变异对照：验证 B 通道（kube-proxy 规则计数器）取数与解析
#
# 背景（台账 #35 续九段盲区 d）：v2 只用 `iptables-save -c -t nat` 取计数器，
# 而 kube-proxy 对「无端点 Service」下的 REJECT 规则挂在 **filter** 表的
# KUBE-SERVICES 链 ⇒ 计数器恒为 status=counter_unavailable。
#
# 用法:
#   bash scripts/selftest_probe_counter_parsing.sh                 # 只跑正向断言
#   bash scripts/selftest_probe_counter_parsing.sh <旧版脚本路径>   # 追加变异对照
#
# 断言（全部通过才 exit 0）:
#   A1 新实现对 `iptables-save -c -t filter` 夹具取到的 pkts/bytes/lines
#      与夹具字面值一致（lines=1 ⇒ 异 IP 规则与近似 IP 规则都未被误命中）
#   A2 legacy / nft-save 两个源同时命中同一规则时，各源独立成行，
#      primary 只计一次（跨源不重复计数）
#   A3 iptables 系全空时回退 nft 原生 ruleset，且能解析出 pkts/bytes
#   B1 变异对照：旧实现（-t nat）对同一 filter 夹具取不到（status=not_found，
#      增量 status=counter_unavailable）
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SCRIPT_UNDER_TEST="${SCRIPT_DIR}/probe-endpointless-service.sh"
LEGACY_SCRIPT="${1:-}"

FIXTURE_IP="10.43.12.34"
PASS=0
FAIL=0

TMPROOT="$(mktemp -d "${TMPDIR:-/tmp}/probe-selftest-XXXXXX")"
# shellcheck disable=SC2329  # cleanup 由 trap 调用
cleanup() {
  rm -rf "$TMPROOT"
}
trap cleanup EXIT

mkdir -p "$TMPROOT/bin" "$TMPROOT/lib" "$TMPROOT/work"
FIXTURE_DIR="$TMPROOT"
export FIXTURE_DIR

# ── 夹具 ───────────────────────────────────────────────────────────────────
# filter 表：目标规则 + 另一个 IP 的规则 + 近似 IP（10.43.12.345）规则
cat > "$TMPROOT/filter.rules" <<'EOF'
# Generated by iptables-save v1.8.7 on Fri Nov 28 00:00:00 2026
*filter
:KUBE-FIREWALL - [0:0]
:KUBE-SERVICES - [0:0]
[7:560] -A KUBE-SERVICES -d 10.43.12.34/32 -p tcp -m comment --comment "kubernetes service shuqing/probe-empty-svc has no endpoints" -j REJECT
[3:240] -A KUBE-SERVICES -d 10.43.56.78/32 -p tcp -m comment --comment "kubernetes service shuqing/other-svc" -j KUBE-SVC-AAA
[99:792] -A KUBE-SERVICES -d 10.43.12.345/32 -p tcp -m comment --comment "boundary probe must not match" -j KUBE-SVC-BBB
COMMIT
EOF

# after 快照：目标规则计数器 +4 包 / +320 字节
cat > "$TMPROOT/filter_after.rules" <<'EOF'
*filter
:KUBE-SERVICES - [0:0]
[11:880] -A KUBE-SERVICES -d 10.43.12.34/32 -p tcp -m comment --comment "kubernetes service shuqing/probe-empty-svc has no endpoints" -j REJECT
[3:240] -A KUBE-SERVICES -d 10.43.56.78/32 -p tcp -m comment --comment "kubernetes service shuqing/other-svc" -j KUBE-SVC-AAA
[99:792] -A KUBE-SERVICES -d 10.43.12.345/32 -p tcp -m comment --comment "boundary probe must not match" -j KUBE-SVC-BBB
COMMIT
EOF

# nft 原生 ruleset（kube-proxy nftables 模式）
cat > "$TMPROOT/nft.ruleset" <<'EOF'
table ip filter {
	chain KUBE-SERVICES {
		ip daddr 10.43.12.34 tcp dport 8080 counter packets 5 bytes 300 reject
	}
}
table ip nat {
	chain KUBE-SERVICES {
		ip daddr 10.43.12.34 tcp dport 8080 counter packets 2 bytes 120 masquerade
	}
}
EOF

# ── 假命令 ────────────────────────────────────────────────────────────────
cat > "$TMPROOT/lib/fake_backend.sh" <<'EOF'
fake_iptables_save() {
  local table="" arg
  while [ $# -gt 0 ]; do
    case "$1" in
      -t) table="$2"; shift 2 ;;
      *) shift ;;
    esac
  done
  # 只在 filter 表返回夹具；nat / mangle / raw 一律为空
  # ⇒ 模拟「规则只存在于 filter 表」，旧实现（-t nat）必然取不到
  local file="${FAKE_TABLE_FILE:-filter.rules}"
  if [ -n "$file" ] && [ "$table" = "filter" ]; then
    cat "$FIXTURE_DIR/$file"
  fi
  exit 0
}
EOF

cat > "$TMPROOT/bin/sudo" <<'EOF'
#!/usr/bin/env bash
exec "$@"
EOF

for fake_name in iptables-save iptables-legacy-save iptables-nft-save; do
  cat > "$TMPROOT/bin/$fake_name" <<EOF
#!/usr/bin/env bash
. "\$FIXTURE_DIR/lib/fake_backend.sh"
name="\$(basename "\$0")"
case "\$name" in
  iptables-save) gate="\${FAKE_ENABLE_SAVE:-yes}" ;;
  iptables-legacy-save) gate="\${FAKE_ENABLE_LEGACY:-no}" ;;
  iptables-nft-save) gate="\${FAKE_ENABLE_NFTSAVE:-no}" ;;
esac
[ "\$gate" = "yes" ] || exit 0
fake_iptables_save "\$@"
EOF
done

cat > "$TMPROOT/bin/nft" <<'EOF'
#!/usr/bin/env bash
[ "${FAKE_ENABLE_NFT:-no}" = "yes" ] || exit 0
cat "$FIXTURE_DIR/nft.ruleset"
exit 0
EOF

chmod +x "$TMPROOT/bin/"*

export PATH="$TMPROOT/bin:$PATH"
export FAKE_LIB="$TMPROOT/lib"

# ── 断言工具 ──────────────────────────────────────────────────────────────
assert_contains() {
  local desc="$1" haystack="$2" needle="$3"
  if printf '%s\n' "$haystack" | grep -qF -- "$needle"; then
    PASS=$((PASS + 1))
    echo "PASS  $desc"
  else
    FAIL=$((FAIL + 1))
    echo "FAIL  $desc"
    echo "      期望包含: $needle"
    printf '%s\n' "$haystack" | sed 's/^/      实际: /'
  fi
}

assert_eq() {
  local desc="$1" expected="$2" actual="$3"
  if [ "$expected" = "$actual" ]; then
    PASS=$((PASS + 1))
    echo "PASS  $desc (= $actual)"
  else
    FAIL=$((FAIL + 1))
    echo "FAIL  $desc 期望=$expected 实际=$actual"
  fi
}

# ── 抽取被测函数 ──────────────────────────────────────────────────────────
if [ ! -f "$SCRIPT_UNDER_TEST" ]; then
  echo "FATAL 找不到被测脚本: $SCRIPT_UNDER_TEST"
  exit 2
fi
sed -n '/^# BEGIN_COUNTER_FUNCTIONS$/,/^# END_COUNTER_FUNCTIONS$/p' "$SCRIPT_UNDER_TEST" \
  | sed '1d;$d' > "$TMPROOT/functions_new.sh"
if [ ! -s "$TMPROOT/functions_new.sh" ]; then
  echo "FATAL 未能从被测脚本抽取 BEGIN/END_COUNTER_FUNCTIONS 段（抽取契约被破坏？）"
  exit 2
fi
# shellcheck disable=SC1090
. "$TMPROOT/functions_new.sh"

echo "=== A1 filter 表夹具：取数与解析 ==="
A1_PREFIX="$TMPROOT/work/a1"
snapshot_rule_counters "$FIXTURE_IP" "$A1_PREFIX" >/dev/null 2>&1 || true
A1_BEFORE="$(emit_rule_counters "$FIXTURE_IP" "$A1_PREFIX" BEFORE host)"
echo "$A1_BEFORE" | sed 's/^/      /'
assert_contains "A1 filter 表命中目标规则的计数器" "$A1_BEFORE" \
  "source=iptables-save table=filter chain=KUBE-SERVICES pkts=7 bytes=560 lines=1 primary=1"

# after 快照切到 filter_after.rules（计数器 +4 包 / +320 字节）
FAKE_TABLE_FILE=filter_after.rules
export FAKE_TABLE_FILE
snapshot_rule_counters "$FIXTURE_IP" "$TMPROOT/work/a1_after" >/dev/null 2>&1 || true
FAKE_TABLE_FILE=filter.rules
export FAKE_TABLE_FILE
A1_DELTA="$(emit_rule_counter_delta "$FIXTURE_IP" "$A1_PREFIX" "$TMPROOT/work/a1_after" host)"
echo "$A1_DELTA" | sed 's/^/      /'
assert_contains "A1 增量 = after - before（+4 包 / +320 字节）" "$A1_DELTA" \
  "source=iptables-save table=filter chain=KUBE-SERVICES pkts=4 bytes=320 primary=1"

echo "=== A2 多源同时命中：各源独立、primary 只计一次 ==="
FAKE_ENABLE_LEGACY=yes
FAKE_ENABLE_NFTSAVE=yes
export FAKE_ENABLE_LEGACY FAKE_ENABLE_NFTSAVE
A2_PREFIX="$TMPROOT/work/a2"
snapshot_rule_counters "$FIXTURE_IP" "$A2_PREFIX" >/dev/null 2>&1 || true
A2_BEFORE="$(emit_rule_counters "$FIXTURE_IP" "$A2_PREFIX" BEFORE host)"
echo "$A2_BEFORE" | sed 's/^/      /'
assert_eq "A2 命中三个 iptables 系源" "3" \
  "$(printf '%s\n' "$A2_BEFORE" | grep -c 'primary=')"
assert_eq "A2 primary 行恰好一条" "1" \
  "$(printf '%s\n' "$A2_BEFORE" | grep -c 'primary=1')"
assert_contains "A2 legacy 源独立成行" "$A2_BEFORE" \
  "source=iptables-legacy-save table=filter chain=KUBE-SERVICES pkts=7 bytes=560 lines=1 primary=0"
assert_contains "A2 nft-save 源独立成行" "$A2_BEFORE" \
  "source=iptables-nft-save table=filter chain=KUBE-SERVICES pkts=7 bytes=560 lines=1 primary=0"

echo "=== A3 iptables 系全空 → 回退 nft 原生 ruleset ==="
FAKE_ENABLE_SAVE=no
FAKE_ENABLE_LEGACY=no
FAKE_ENABLE_NFTSAVE=no
FAKE_ENABLE_NFT=yes
export FAKE_ENABLE_SAVE FAKE_ENABLE_LEGACY FAKE_ENABLE_NFTSAVE FAKE_ENABLE_NFT
A3_PREFIX="$TMPROOT/work/a3"
snapshot_rule_counters "$FIXTURE_IP" "$A3_PREFIX" >/dev/null 2>&1 || true
A3_BEFORE="$(emit_rule_counters "$FIXTURE_IP" "$A3_PREFIX" BEFORE host)"
echo "$A3_BEFORE" | sed 's/^/      /'
assert_contains "A3 nft 原生 filter 表计数被解析" "$A3_BEFORE" \
  "source=nft table=filter chain=KUBE-SERVICES pkts=5 bytes=300 lines=1 primary=1"
assert_contains "A3 nft 原生 nat 表计数被解析" "$A3_BEFORE" \
  "source=nft table=nat chain=KUBE-SERVICES pkts=2 bytes=120 lines=1 primary=0"

echo "=== B1 变异对照：旧实现（-t nat）对同一 filter 夹具取不到 ==="
if [ -z "$LEGACY_SCRIPT" ]; then
  echo "SKIP  B1 未提供旧版脚本路径，跳过变异对照（正例断言仍有效）"
else
  if [ ! -f "$LEGACY_SCRIPT" ]; then
    echo "FATAL 旧版脚本不存在: $LEGACY_SCRIPT"
    exit 2
  fi
  # 旧版函数的取数段：注释头「# 宿主机 nat 表里命中…」到「# 启动抓包…」
  sed -n '/^# 宿主机 nat 表里命中/,/^# 启动抓包/p' "$LEGACY_SCRIPT" \
    | sed '$d' > "$TMPROOT/functions_old.sh"
  if [ ! -s "$TMPROOT/functions_old.sh" ]; then
    echo "FATAL 未能从旧版脚本抽取计数器函数段（旧版结构已变？）"
    exit 2
  fi
  # 旧版函数名与新版同名 ⇒ 放到独立 bash 进程里跑，避免互相覆盖
  OLD_OUT="$(bash -c '
    . "$1/functions_old.sh"
    snapshot_nat_counters "$2" "$1/old_snapshot" || true
    emit_rule_counters "$2" "$1/old_snapshot" BEFORE
    emit_rule_counter_delta "$2" "$1/old_snapshot" "$1/old_snapshot"
  ' _ "$TMPROOT" "$FIXTURE_IP" 2>&1)"
  echo "$OLD_OUT" | sed 's/^/      /'
  assert_contains "B1 旧实现取不到规则（status=not_found）" "$OLD_OUT" \
    "RULE_COUNTER_BEFORE ip=${FIXTURE_IP} pkts=- bytes=- lines=0 status=not_found"
  assert_contains "B1 旧实现增量不可用（status=counter_unavailable）" "$OLD_OUT" \
    "RULE_COUNTER_DELTA ip=${FIXTURE_IP} pkts=- bytes=- status=counter_unavailable"
fi

echo "============================================================"
echo "SELFTEST RESULT: PASS=${PASS} FAIL=${FAIL}"
if [ "$FAIL" -eq 0 ]; then
  echo "SELFTEST STATUS: PASS"
  exit 0
fi
echo "SELFTEST STATUS: FAIL"
exit 1
